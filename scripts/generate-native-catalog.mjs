import { providers, feedUrl } from "../shared/providers.js";
import brandIcons from "../src/brand-icons.json" with { type: "json" };
import { mkdirSync, writeFileSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

// Android resource names accept lowercase letters, digits and underscores and
// cannot start with a digit. Every provider id is checked instead of silently
// rewritten: a renamed provider must fail the build, not ship a missing icon.
export function drawableName(id) {
  if (!/^[a-z][a-z0-9_]*$/.test(id))
    throw new Error(
      `Provider id "${id}" cannot become an Android resource name`,
    );
  return `ic_provider_${id}`;
}

const PARAMETERS = {
  m: 2,
  l: 2,
  h: 1,
  v: 1,
  c: 6,
  s: 4,
  q: 4,
  t: 2,
  a: 7,
  z: 0,
};
const NUMBER = /^[+-]?(?:\d+\.\d+|\.\d+|\d+)(?:[eE][+-]?\d+)?/;

/**
 * Android's PathParser splits numbers on whitespace, commas, a sign and a
 * second decimal point — it has no notion of an arc flag. SVG optimisers emit
 * arcs with the flags packed against the next number ("a3 3 0 013-3"), which
 * that tokenizer reads as one number too few, so the drawable either draws the
 * wrong shape or fails to inflate. Re-emitting the same tokens with explicit
 * separators is geometry-neutral and costs a few bytes per icon.
 */
export function normalizePath(path) {
  if (!/^[MmLlHhVvCcSsQqTtAaZz0-9eE+\-.,\s]+$/.test(path))
    throw new Error("Brand icon path contains characters Android cannot parse");
  const source = path.trim();
  const commands = [];
  let at = 0;
  const skip = () => {
    while (at < source.length && /[\s,]/.test(source[at])) at++;
  };
  const number = () => {
    skip();
    const match = NUMBER.exec(source.slice(at));
    if (!match)
      throw new Error(`Unreadable number at offset ${at} of "${source}"`);
    at += match[0].length;
    return match[0];
  };
  // An arc flag is exactly one character, whether or not a separator follows.
  const flag = () => {
    skip();
    const value = source[at];
    if (value !== "0" && value !== "1")
      throw new Error(`Arc flag must be 0 or 1 at offset ${at} of "${source}"`);
    at++;
    return value;
  };
  while (at < source.length) {
    skip();
    if (at >= source.length) break;
    const command = source[at];
    const step = PARAMETERS[command.toLowerCase()];
    if (step === undefined)
      throw new Error(`Unknown path command "${command}"`);
    at++;
    const values = [];
    for (;;) {
      skip();
      if (step === 0) break;
      if (at >= source.length || !NUMBER.test(source.slice(at))) break;
      for (let n = 0; n < step; n++)
        values.push(
          command.toLowerCase() === "a" && (n === 3 || n === 4)
            ? flag()
            : number(),
        );
    }
    if (step > 0 && values.length === 0)
      throw new Error(`Path command "${command}" has no parameters`);
    commands.push(command + values.join(" "));
  }
  if (!commands.length) throw new Error("Brand icon path is empty");
  return commands.join(" ");
}

export function vectorDrawable(rawPath) {
  const path = normalizePath(rawPath);
  return `<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="${path}" />
</vector>
`;
}

export function nativeCatalog() {
  return providers.map((p) => {
    if (!brandIcons[p.id])
      throw new Error(`Provider "${p.id}" has no brand icon`);
    return {
      id: p.id,
      name: p.name,
      url: feedUrl(p),
      format: p.format || "statuspage",
      ...(p.componentId ? { componentId: p.componentId } : {}),
      color: p.color,
      icon: drawableName(p.id),
    };
  });
}

// The widgets resolve icons through a generated switch instead of
// Resources.getIdentifier so a missing drawable fails compilation.
export function iconLookup(catalog) {
  return `package app.pulse.status;

/** Generated by scripts/generate-native-catalog.mjs. Do not edit. */
final class PulseIcons {
    private PulseIcons() {}
    static int drawable(String id) {
        switch(id) {
${catalog.map((p) => `            case "${p.id}": return R.drawable.${p.icon};`).join("\n")}
            default: return R.drawable.ic_pulse_notification_logo;
        }
    }
}
`;
}

export function generate(root = process.cwd()) {
  const assets = join(root, "android/app/src/main/assets");
  const drawables = join(root, "android/app/src/main/res/drawable");
  const java = join(root, "android/app/src/main/java/app/pulse/status");
  const catalog = nativeCatalog();

  for (const directory of [assets, drawables, java])
    mkdirSync(directory, { recursive: true });
  writeFileSync(join(assets, "pulse-catalog.json"), JSON.stringify(catalog));

  const wanted = new Set(catalog.map((p) => `${p.icon}.xml`));
  for (const file of readdirSync(drawables))
    if (file.startsWith("ic_provider_") && !wanted.has(file))
      rmSync(join(drawables, file));
  for (const provider of catalog)
    writeFileSync(
      join(drawables, `${provider.icon}.xml`),
      vectorDrawable(brandIcons[provider.id]),
    );
  writeFileSync(join(java, "PulseIcons.java"), iconLookup(catalog));
  return catalog;
}

// Importing this module must stay side-effect free: the drift tests read the
// committed output rather than regenerating it underneath themselves.
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  generate();
